        /// <summary>
        /// Signed distance to the module frame (negative inside). Stitched worlds measure to the
        /// outer rim only, so the seams between modules are open floor.
        /// </summary>
        public double HexDist(double x, double z)
        {
            if (HexCenters.Count > 1) return _frame.Dist(x, z);
            double ax = Math.Abs(x - HexCenters[0].x);
            double az = Math.Abs(z - HexCenters[0].z);
            return JsMath.Max(ax, ax * 0.5 + az * 0.8660254) - Apothem;
        }

        private double Sample(float[] arr, double x, double z)
        {
            FieldGrid g = Grid;
            double fx = JsMath.Clamp((x - g.MinX) / g.Cell, 0, g.Nx - 1.001);
            double fz = JsMath.Clamp((z - g.MinZ) / g.Cell, 0, g.Nz - 1.001);
            int ix = JsMath.ToInt32(fx);
            int iz = JsMath.ToInt32(fz);
            double tx = fx - ix;
            double tz = fz - iz;
            int i = iz * g.Nx + ix;
            double a = arr[i];
            double b = arr[i + 1];
            double c = arr[i + g.Nx];
            double d = arr[i + g.Nx + 1];
            return (a * (1 - tx) + b * tx) * (1 - tz) + (c * (1 - tx) + d * tx) * tz;
        }

        /// <summary>Signed distance to the canyon edge (negative = canyon floor). Shapes the terrain.</summary>
        public double PathDist(double x, double z)
        {
            return Sample(Grid.D, x, z);
        }

        /// <summary>Walkable signed distance: inside the canyon and inside the hexagon frame (negative = walkable).</summary>
        public double Dist(double x, double z)
        {
            return JsMath.Max(Sample(Grid.D, x, z), HexDist(x, z) + Cfg.FrameWallMargin);
        }

        /// <summary>Distance to the nearest recognized centreline.</summary>
        public double CenterDist(double x, double z)
        {
            return Sample(Grid.C, x, z);
        }

        /// <summary>Half-width of the nearest corridor.</summary>
        public double HalfWidth(double x, double z)
        {
            return Sample(Grid.Hw, x, z);
        }

        /// <summary>Terrain height (Y) at (x, z).</summary>
        public double Height(double x, double z)
        {
            return Sample(Grid.H, x, z);
        }

        /// <summary>Gradient of the walkable distance (points away from the walkable area).</summary>
        public (double x, double z) GradDist(double x, double z)
        {
            double e = Grid.Cell;
            double gx = (Dist(x + e, z) - Dist(x - e, z)) / (2 * e);
            double gz = (Dist(x, z + e) - Dist(x, z - e)) / (2 * e);
            return (gx, gz);
        }

        /// <summary>Unit floor normal from the height field (y up).</summary>
        public (double x, double y, double z) Normal(double x, double z)
        {
            double e = Grid.Cell;
            double hx = (Height(x + e, z) - Height(x - e, z)) / (2 * e);
            double hz = (Height(x, z + e) - Height(x, z - e)) / (2 * e);
            // three.js: out.set(-hx, 1, -hz).normalize() = multiplyScalar(1 / (length() || 1))
            double nx = -hx;
            double ny = 1;
            double nz = -hz;
            double inv = 1 / JsMath.OrOne(Math.Sqrt(nx * nx + ny * ny + nz * nz));
            return (nx * inv, ny * inv, nz * inv);
        }

        /// <summary>
        /// A junction near the middle of the module, with a heading along one of its edges.
        /// <c>heading</c> = atan2(dx, dz): the yaw that turns +Z toward +X (Unity: Euler(0, heading·Rad2Deg, 0)).
        /// </summary>
        public (double x, double z, double heading) SpawnPoint()
        {
            var candidates = new List<Node>();
            foreach (Node n in Nodes) if (n.Degree >= 3 && n.Inside) candidates.Add(n);
            List<Node> pool = candidates;
            if (pool.Count == 0)
            {
                pool = new List<Node>();
                foreach (Node n in Nodes) if (n.Inside) pool.Add(n);
            }
            List<Node> list = pool.Count > 0 ? pool : Nodes;
            if (list.Count == 0) throw new InvalidOperationException("PathField has no nodes");
            Node best = list[0];
            double bestScore = double.PositiveInfinity;
            foreach (Node n in list)
            {
                double score = JsMath.Hypot(n.X, n.Z) - n.Degree * 3;
                if (score < bestScore)
                {
                    bestScore = score;
                    best = n;
                }
            }
            Edge edge = null;
            foreach (Edge e in Edges)
            {
                if (e.Source == best.Id || e.Target == best.Id)
                {
                    edge = e;
                    break;
                }
            }
            double heading = 0;
            if (edge != null)
            {
                List<double[]> pts = edge.Source == best.Id ? edge.Pts : JsMath.Reversed(edge.Pts);
                double[] p = pts[Math.Min(4, pts.Count - 1)];
                heading = JsMath.Atan2(p[0] - best.X, p[1] - best.Z);
            }
            return (best.X, best.Z, heading);
        }
    }
