// Ant Garden core — port of PathField from src/pathfield.js.
//
// Turns a Path Recognize network (schemaVersion 2.x) into a walkable canyon framed by a regular hexagon:
//   PathDist(x, z)  signed distance to the canyon edge (negative = canyon floor)
//   Dist(x, z)      walkable distance: canyon AND inside the hexagon frame
//   Height(x, z)    floor → moss bank → plateau profile
// Everything the player can touch is derived from the recognized path.
//
// Coordinates: world X = image x (right), world Z = image y (down the image), Y = up (Height).
// Used directly as Unity (x, Height(x, z), z), the world is the mirror image of the three.js prototype
// (three.js is right-handed, Unity left-handed); gameplay is unaffected. To see the prototype's
// orientation instead, negate z going in and coming out. 1 world unit ≈ 1 ant body length.
// The distance and height grids are float32, as in JavaScript.
using System;
using System.Collections.Generic;

namespace AntGarden.Core
{
    /// <summary>A node of the canyon network: junction, endpoint, or (stitched worlds) port / split / bridge.</summary>
    public sealed class Node
    {
        /// <summary>Node id ("n3"; stitched worlds prefix the module: "m1:n3", "m0:port2", …).</summary>
        public string Id;
        /// <summary>"junction" | "endpoint" | … (from the network).</summary>
        public string Type;
        /// <summary>World position.</summary>
        public double X, Z;
        /// <summary>Widest half-width of the incident edges.</summary>
        public double Hw;
        /// <summary>Chamber radius (junctions and dead ends; clamped to ChamberMin..ChamberMax unless degree is 2).</summary>
        public double Clear;
        /// <summary>Number of incident edge ends (a self-loop counts 4, as in the prototype).</summary>
        public int Degree;
        /// <summary>The node touches the source image border.</summary>
        public bool Boundary;
        /// <summary>More than 2 units inside the hexagon frame.</summary>
        public bool Inside;
    }

    /// <summary>A canyon corridor: resampled centreline with a half-width per point.</summary>
    public sealed class Edge
    {
        /// <summary>Edge id ("e2"; stitched: "m1:e2", "link0", "branch5", "bridge7", …).</summary>
        public string Id;
        /// <summary>Source / target node ids.</summary>
        public string Source, Target;
        /// <summary>Centreline points as [x, z] (world units, ≈ ResampleStep apart).</summary>
        public List<double[]> Pts;
        /// <summary>Half-width at each point of <see cref="Pts"/>.</summary>
        public List<double> Hws;
        /// <summary>Max of <see cref="Hws"/>.</summary>
        public double Hw;
        /// <summary>Polyline length.</summary>
        public double Length;
        /// <summary>Generated by the stitcher (link / branch / bridge between modules).</summary>
        public bool Connector;
        /// <summary>Path Recognize marked part of this path as inferred.</summary>
        public bool Inferred;
    }

    /// <summary>A point where the canyon runs out through the hexagon frame.</summary>
    public sealed class Exit
    {
        /// <summary>Last centreline point before the frame.</summary>
        public double X, Z;
        /// <summary>Unit direction pointing out of the frame.</summary>
        public double DirX, DirZ;
        /// <summary>The edge that leaves the frame here.</summary>
        public string EdgeId;
    }

    /// <summary>One module of a stitched world.</summary>
    public sealed class ModuleInfo
    {
        /// <summary>Module id ("path-010").</summary>
        public string Id;
        /// <summary>Rotation in degrees (multiples of 60) turning +x toward +z, i.e. Unity yaw = -Rot.</summary>
        public int Rot;
        /// <summary>Hexagon centre (world).</summary>
        public double X, Z;
    }

    /// <summary>Axis-aligned bounds on the XZ plane.</summary>
    public struct Bounds2
    {
        /// <summary>Extent along X.</summary>
        public double MinX, MaxX;
        /// <summary>Extent along Z.</summary>
        public double MinZ, MaxZ;
    }

    /// <summary>
    /// The sampled fields (float32, row-major: index = iz * Nx + ix, sample (ix, iz) sits at
    /// (MinX + ix * Cell, MinZ + iz * Cell)). Read-only: do not modify the arrays.
    /// </summary>
    public sealed class FieldGrid
    {
        /// <summary>Position of sample (0, 0).</summary>
        public double MinX, MinZ;
        /// <summary>Sample spacing (PathConfig.FieldCell).</summary>
        public double Cell;
        /// <summary>Sample counts.</summary>
        public int Nx, Nz;
        /// <summary>Signed distance to the canyon edge (<see cref="PathField.PathDist"/>).</summary>
        public float[] D;
        /// <summary>Distance to the nearest centreline (<see cref="PathField.CenterDist"/>).</summary>
        public float[] C;
        /// <summary>Terrain height (<see cref="PathField.Height"/>).</summary>
        public float[] H;
        /// <summary>Half-width of the nearest corridor (<see cref="PathField.HalfWidth"/>).</summary>
        public float[] Hw;
    }

    /// <summary>
    /// The walkable canyon derived from a recognized ant-nest path network (or several stitched ones).
    /// </summary>
    /// <remarks>
    /// Construction is self-contained (no shared mutable state), so it may run on a worker thread.
    /// Once built, every query method only reads, so one field can be queried from several threads at
    /// once. The public lists and arrays are the field's own data: treat them as read-only.
    /// </remarks>
    public sealed class PathField
    {
        private static readonly double SQRT3 = Math.Sqrt(3);

        /// <summary>The configuration (a private copy taken at construction).</summary>
        public PathConfig Cfg;
        /// <summary>Source image name ("path-013.png"), or "path-010 + path-013" for stitched worlds.</summary>
        public string Name;
        /// <summary>Resolved width mode: "designed" or "measured" (or whatever unknown mode was configured).</summary>
        public string WidthMode;
        /// <summary>Nodes with at least one incident edge, in network order.</summary>
        public List<Node> Nodes;
        /// <summary>Canyon corridors.</summary>
        public List<Edge> Edges;
        /// <summary>Where the canyon runs out through the frame.</summary>
        public List<Exit> Exits;
        /// <summary>Hexagon centres: one per module ((0, 0) for a single module).</summary>
        public List<(double x, double z)> HexCenters;
        /// <summary>Hexagon circumradius and apothem.</summary>
        public double R, Apothem;
        /// <summary>Union of the module hexagons plus a 1.5-unit margin (also the grid extent).</summary>
        public Bounds2 Bounds;
        /// <summary>All hexagon sides; <see cref="FrameEdge.Shared"/> marks seams between modules.</summary>
        public List<FrameEdge> FrameEdges;
        /// <summary>Stitched worlds: one entry per module. Empty for a single module.</summary>
        public List<ModuleInfo> Modules;
        /// <summary>Sum of all edge lengths.</summary>
        public double TotalLength;

        /// <summary>World units per image pixel (1 for stitched worlds).</summary>
        public double Scale;
        /// <summary>Source image size in pixels (0 for stitched worlds).</summary>
        public double ImageWidth, ImageHeight;
        /// <summary>Area of grid samples with <see cref="Dist"/> &lt; 0.</summary>
        public double WalkableArea;
        /// <summary>The sampled float32 fields behind the queries.</summary>
        public FieldGrid Grid;
        /// <summary>The field's noise (seeded with Seed + 11), the same instance the canyon shape uses.</summary>
        public Noise Noise;

        private HexFrame _frame; // stitched worlds: outer-rim distance

        /// <summary>Builds the canyon of one module (JS: <c>new PathField(network, cfg)</c>).</summary>
        /// <exception cref="InvalidNetworkException">The network is not a usable Path Recognize 2.x network.</exception>
        public PathField(NetworkData net, PathConfig cfg) : this(net, cfg, true)
        {
        }

        private PathField(NetworkData net, PathConfig cfg, bool full)
        {
            if (net == null) throw new ArgumentNullException(nameof(net));
            Setup(cfg);
            List<Node> raw = InitNetwork(net);
            Finish(raw, full);
        }

        private PathField()
        {
        }

        private void Setup(PathConfig cfg)
        {
            Cfg = (cfg ?? PathConfig.Default()).Clone();
            Noise = new Noise(Cfg.Seed + 11.0);
            HexCenters = new List<(double x, double z)> { (0.0, 0.0) };
            Modules = new List<ModuleInfo>();
            Exits = new List<Exit>();
        }

        /// <summary>
        /// Module geometry only (nodes, edges, frame) without the grids and exits: what the stitcher
        /// reads from each module. Identical nodes and edges to the full constructor.
        /// </summary>
        internal static PathField ModuleOnly(NetworkData net, PathConfig cfg)
        {
            return new PathField(net, cfg, false);
        }

        /// <summary>
        /// Builds a stitched world from edges and nodes already in world units (JS: the
        /// <c>composite</c> constructor path). Used by <see cref="Stitcher"/>; the inputs are copied.
        /// </summary>
        /// <param name="r">shared hexagon circumradius</param>
        /// <param name="centers">hexagon centres</param>
        /// <param name="edges">edges (Id, Source, Target, Pts, Hws, Connector, Inferred are read)</param>
        /// <param name="nodes">nodes (Id, X, Z, Type, Boundary are read)</param>
        /// <param name="name">world name</param>
        /// <param name="modules">module placement</param>
        /// <param name="cfg">configuration</param>
        public static PathField FromComposite(double r, IList<(double x, double z)> centers, IList<Edge> edges, IList<Node> nodes,
            string name, IList<ModuleInfo> modules, PathConfig cfg)
        {
            var f = new PathField();
            f.Setup(cfg);
            f.Name = name ?? "";
            f.ImageWidth = 0;
            f.ImageHeight = 0;
            f.Scale = 1;
            f.R = r;
            f.Apothem = (r * SQRT3) / 2;
            f.HexCenters = new List<(double x, double z)>(centers);
            f.WidthMode = "designed";
            f.Edges = new List<Edge>(edges.Count);
            foreach (Edge e in edges)
            {
                f.Edges.Add(new Edge
                {
                    Id = e.Id,
                    Source = e.Source,
                    Target = e.Target,
                    Pts = new List<double[]>(e.Pts),
                    Hws = new List<double>(e.Hws),
                    Hw = JsMath.MaxOf(e.Hws),
                    Length = PolyLength(e.Pts),
                    Connector = e.Connector,
                    Inferred = e.Inferred,
                });
            }
            if (modules != null)
            {
                foreach (ModuleInfo m in modules) f.Modules.Add(new ModuleInfo { Id = m.Id, Rot = m.Rot, X = m.X, Z = m.Z });
            }
            var raw = new List<Node>(nodes.Count);
            foreach (Node n in nodes) raw.Add(new Node { Id = n.Id, X = n.X, Z = n.Z, Type = n.Type, Boundary = n.Boundary });
            f.Finish(raw, true);
            return f;
        }

        // ---- construction ---------------------------------------------------------------------

        private List<Node> InitNetwork(NetworkData network)
        {
            network.Validate();
            PathConfig cfg = Cfg;
            double W = network.ImageWidth;
            double H = network.ImageHeight;
            double s = JsMath.Truthy(cfg.WorldSize) ? cfg.WorldSize / JsMath.Max(W, H) : cfg.PxToWorld;
            Scale = s;
            ImageWidth = W;
            ImageHeight = H;
            Name = network.Name ?? "";

            // Regular pointy-top hexagon. Start from the one inscribed in the image, then grow it
            // until every inner feature (junctions, loops, spirals) fits; only the tails that run
            // off the image edge may cross the frame, and they are extended to reach it.
            double halfW = (W * s) / 2;
            double halfH = (H * s) / 2;
            double borderW = cfg.FrameBorderMargin * JsMath.Max(W, H) * s;
            bool NearBorder(double x, double z) => Math.Abs(x) > halfW - borderW || Math.Abs(z) > halfH - borderW;
            double Support(double x, double z) => JsMath.Max(Math.Abs(x), Math.Abs(x) * 0.5 + Math.Abs(z) * 0.8660254) / 0.8660254;
            double r = JsMath.Min((W * s) / SQRT3, (H * s) / 2) * cfg.FrameFill;
            foreach (NetworkEdge e in network.Edges)
            {
                if (e.Points == null) continue;
                foreach (double[] p in e.Points)
                {
                    double x = (p[0] - W / 2) * s;
                    double z = (p[1] - H / 2) * s;
                    if (!NearBorder(x, z)) r = JsMath.Max(r, Support(x, z) + cfg.FrameInnerPad);
                }
            }
            if (cfg.FrameForceR.HasValue && JsMath.Truthy(cfg.FrameForceR.Value)) r = JsMath.Max(r, cfg.FrameForceR.Value); // stitched modules share one size
            R = r;
            Apothem = (r * SQRT3) / 2;

            var widths = new List<double>();
            foreach (NetworkEdge e in network.Edges)
            {
                if (e.MeanWidthIsNumber && JsMath.IsFinite(e.MeanWidthPx) && e.MeanWidthPx > 0) widths.Add(e.MeanWidthPx);
            }
            widths.Sort();
            double medianPx = widths.Count > 0 ? widths[widths.Count >> 1] : 20;
            // Canyon width is a design decision. 'designed' (default): every path gets its own
            // character around fixedWidth, and the photo's measured widths only say which paths
            // are broader or narrower than the rest. 'measured': the photo's widths as they are.
            // 'auto': measured, unless the drawing is hairline.
            string mode = cfg.WidthMode ?? "designed";
            WidthMode = mode == "auto" ? (medianPx * s < cfg.LineDrawingMaxWidth ? "designed" : "measured") : mode;

            var edgeRng = new Rng(cfg.Seed + 77.0);
            Edges = new List<Edge>();
            int ei = 0;
            foreach (NetworkEdge e in network.Edges)
            {
                if (e.Points == null || e.Points.Count < 2) continue;
                var world = new List<double[]>(e.Points.Count);
                foreach (double[] p in e.Points) world.Add(new[] { (p[0] - W / 2) * s, (p[1] - H / 2) * s });
                List<double[]> pts = Resample(world, cfg.ResampleStep);
                var hws = new List<double>(pts.Count);
                if (WidthMode != "measured")
                {
                    // Every path gets its own character: some are broad avenues, some narrow
                    // tunnels, and each swells and pinches along its length.
                    double rel = e.MeanWidthPx > 0 ? JsMath.Clamp(Math.Pow(e.MeanWidthPx / medianPx, cfg.MeasuredInfluence), 0.7, 1.45) : 1;
                    double mult = JsMath.Lerp(cfg.EdgeWidthRange[0], cfg.EdgeWidthRange[1], edgeRng.Next()) * rel;
                    double acc = 0;
                    for (int i = 0; i < pts.Count; i++)
                    {
                        double[] p = pts[i];
                        if (i > 0) acc += JsMath.Hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]);
                        double v = Noise.Noise2(acc * cfg.WidthFrequency + ei * 17.3, ei * 3.1);
                        double pinch = JsMath.Smoothstep(0.45, 0.85, Noise.Noise2(acc * 0.03 + 99 + ei, ei * 1.7)) * cfg.Pinch;
                        double hw = (cfg.FixedWidth / 2) * mult * (1 + cfg.WidthVariation * v) * (1 - pinch);
                        hws.Add(JsMath.Clamp(hw, cfg.MinHalfWidth, cfg.MaxHalfWidth));
                    }
                }
                else
                {
                    double w = JsMath.Clamp((e.MeanWidthPx > 0 ? e.MeanWidthPx : medianPx) * s * cfg.WidthScale, cfg.MinWidth, cfg.MaxWidth);
                    for (int i = 0; i < pts.Count; i++) hws.Add(w / 2);
                }
                // Tails that ran off the image edge are continued straight on until they cross the frame.
                for (int pass = 0; pass < 2; pass++)
                {
                    bool atEnd = pass == 0;
                    List<double[]> list = atEnd ? pts : JsMath.Reversed(pts);
                    List<double> hl = atEnd ? hws : JsMath.Reversed(hws);
                    double lx = list[list.Count - 1][0];
                    double lz = list[list.Count - 1][1];
                    if (!NearBorder(lx, lz) || list.Count < 2) continue;
                    double qx = list[list.Count - 2][0];
                    double qz = list[list.Count - 2][1];
                    double len = JsMath.OrOne(JsMath.Hypot(lx - qx, lz - qz));
                    double dx = (lx - qx) / len;
                    double dz = (lz - qz) / len;
                    double step = cfg.ResampleStep;
                    int k = 1;
                    while (HexDist(lx + dx * k * step, lz + dz * k * step) < 3 && k < 400)
                    {
                        list.Add(new[] { lx + dx * k * step, lz + dz * k * step });
                        hl.Add(hl[hl.Count - 1]);
                        k++;
                    }
                    if (!atEnd)
                    {
                        list.Reverse();
                        hl.Reverse();
                        pts.Clear();
                        pts.AddRange(list);
                        hws.Clear();
                        hws.AddRange(hl);
                    }
                }
                Edges.Add(new Edge
                {
                    Id = e.Id,
                    Source = e.Source,
                    Target = e.Target,
                    Pts = pts,
                    Hws = hws,
                    Hw = JsMath.MaxOf(hws),
                    Inferred = e.InferredFraction > 0,
                    Length = PolyLength(pts),
                });
                ei++;
            }

            var raw = new List<Node>(network.Nodes.Count);
            foreach (NetworkNode n in network.Nodes)
            {
                raw.Add(new Node { Id = n.Id, X = (n.X - W / 2) * s, Z = (n.Y - H / 2) * s, Type = n.Type, Boundary = n.Boundary });
            }
            return raw;
        }

        // A JS Map key for an id that may be undefined.
        private static string Key(string id)
        {
            return id ?? "\u0000undefined";
        }

        private void Finish(List<Node> rawNodes, bool full)
        {
            PathConfig pc = Cfg;
            if (HexCenters.Count > 1) _frame = new HexFrame(HexCenters, R);

            // JS Map semantics: insertion order of the first occurrence, a repeated id replaces the value.
            var byId = new Dictionary<string, Node>(StringComparer.Ordinal);
            var order = new List<string>();
            foreach (Node n in rawNodes)
            {
                string key = Key(n.Id);
                if (!byId.ContainsKey(key)) order.Add(key);
                byId[key] = new Node { Id = n.Id, X = n.X, Z = n.Z, Type = n.Type, Boundary = n.Boundary, Hw = 0, Degree = 0, Clear = 0 };
            }
            foreach (Edge e in Edges)
            {
                bool loop = string.Equals(e.Source, e.Target, StringComparison.Ordinal);
                for (int end = 0; end < 2; end++)
                {
                    // JS iterates [source, target], so a self-loop adds 2 twice (degree 4) — kept as is.
                    Node n;
                    if (byId.TryGetValue(Key(end == 0 ? e.Source : e.Target), out n))
                    {
                        n.Hw = JsMath.Max(n.Hw, e.Hw);
                        n.Degree += loop ? 2 : 1;
                    }
                }
            }
            Nodes = new List<Node>();
            foreach (string key in order)
            {
                Node n = byId[key];
                if (n.Degree > 0) Nodes.Add(n);
            }
            foreach (Node n in Nodes)
            {
                n.Clear = n.Hw * (n.Degree >= 3 ? pc.JunctionClearing : n.Degree == 1 ? pc.EndpointClearing : 1);
                if (n.Degree != 2) n.Clear = JsMath.Clamp(n.Clear, pc.ChamberMin, pc.ChamberMax);
                n.Inside = HexDist(n.X, n.Z) < -2;
            }
            double total = 0;
            foreach (Edge e in Edges) total += e.Length;
            TotalLength = total;

            // bounds: union of all module hexagons
            const double m = 1.5;
            var xs = new List<double>(HexCenters.Count);
            var zs = new List<double>(HexCenters.Count);
            foreach (var c in HexCenters)
            {
                xs.Add(c.x);
                zs.Add(c.z);
            }
            Bounds = new Bounds2
            {
                MinX = JsMath.MinOf(xs) - Apothem - m,
                MaxX = JsMath.MaxOf(xs) + Apothem + m,
                MinZ = JsMath.MinOf(zs) - R - m,
                MaxZ = JsMath.MaxOf(zs) + R + m,
            };
            FrameEdges = new HexFrame(HexCenters, R).Edges;
            if (!full) return;
            BuildGrids();
            Exits = FindExits();
        }

        private static double PolyLength(List<double[]> pts)
        {
            double len = 0;
            for (int i = 1; i < pts.Count; i++) len += JsMath.Hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
            return len;
        }

        /// <summary>Resample a polyline to roughly uniform spacing, keeping both endpoints.</summary>
        private static List<double[]> Resample(List<double[]> pts, double step)
        {
            double total = PolyLength(pts);
            if (total < step * 1.5) return new List<double[]> { pts[0], pts[pts.Count - 1] };
            double nd = JsMath.Max(1, JsMath.Round(total / step));
            int n = double.IsNaN(nd) ? 0 : (int)nd;
            var outPts = new List<double[]>(Math.Max(n, 1) + 1) { pts[0] };
            int seg = 1;
            double segStart = 0;
            double segLen = JsMath.Hypot(pts[1][0] - pts[0][0], pts[1][1] - pts[0][1]);
            for (int k = 1; k < n; k++)
            {
                double target = ((double)k / n) * total;
                while (segStart + segLen < target && seg < pts.Count - 1)
                {
                    segStart += segLen;
                    seg++;
                    segLen = JsMath.Hypot(pts[seg][0] - pts[seg - 1][0], pts[seg][1] - pts[seg - 1][1]);
                }
                double t = segLen > 0 ? (target - segStart) / segLen : 0;
                double[] a = pts[seg - 1];
                double[] b = pts[seg];
                outPts.Add(new[] { a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t });
            }
            outPts.Add(pts[pts.Count - 1]);
            return outPts;
        }

        private void BuildGrids()
        {
            double cell = Cfg.FieldCell;
            double minX = Bounds.MinX, minZ = Bounds.MinZ, maxX = Bounds.MaxX, maxZ = Bounds.MaxZ;
            int nx = (int)Math.Ceiling((maxX - minX) / cell) + 1;
            int nz = (int)Math.Ceiling((maxZ - minZ) / cell) + 1;
            double band = JsMath.Max(maxX - minX, maxZ - minZ);
            double far = band + 1;
            int count = nx * nz;
            var d = new float[count];
            var c = new float[count];
            var hwAt = new float[count];
            float farF = (float)far;
            for (int i = 0; i < count; i++)
            {
                d[i] = farF;
                c[i] = 1e3f;
            }

            // Every segment and every chamber reaches the whole grid (reach = band), see FieldStamper.
            var target = new FieldStamper.Target { D = d, C = c, Hw = hwAt, Nx = nx, Nz = nz, MinX = minX, MinZ = minZ, Cell = cell, Band = band };
            FieldStamper.StampSegments(Edges, target);
            // Chambers at junctions and inner dead ends: irregular, organic outlines.
            FieldStamper.StampChambers(Nodes, Noise, Cfg.ChamberNoise, target);

            var h = new float[count];
            for (int iz = 0; iz < nz; iz++)
            {
                for (int ix = 0; ix < nx; ix++)
                {
                    int idx = iz * nx + ix;
                    h[idx] = (float)HeightFormula(minX + ix * cell, minZ + iz * cell, d[idx]);
                }
            }
            Grid = new FieldGrid { MinX = minX, MinZ = minZ, Nx = nx, Nz = nz, Cell = cell, D = d, C = c, H = h, Hw = hwAt };

            // JS counts dist(x, z) < 0, i.e. max(pathDist, hexDist + wallMargin) < 0: both must be negative
            // (NaN fails either way), so the frame distance is only needed on the canyon floor.
            int walk = 0;
            double wallMargin = Cfg.FrameWallMargin;
            for (int iz = 0; iz < nz; iz++)
            {
                double z = minZ + iz * cell;
                for (int ix = 0; ix < nx; ix++)
                {
                    double x = minX + ix * cell;
                    if (Sample(d, x, z) < 0 && HexDist(x, z) + wallMargin < 0) walk++;
                }
            }
            WalkableArea = walk * cell * cell;
        }

        /// <summary>Canyon floor, then a mossy bank rising to a plateau where the forest stands.</summary>
        private double HeightFormula(double x, double z, double d)
        {
            PathConfig g = Cfg;
            double n = Noise.Fbm2(x * 0.06, z * 0.06, 3) * g.GroundUndulation;
            double bank = g.GroundBankHeight * JsMath.Smoothstep(-0.9, g.GroundBankWidth, d);
            // JS: n + bank + lumps + plateau. A term whose smoothstep weight is exactly 0 is ±0 and leaves a
            // non-zero running sum unchanged, so its noise lookup is skipped then (same bits, less work).
            double sum = n + bank;
            double wl = JsMath.Smoothstep(-0.2, g.GroundBankWidth * 0.7, d);
            double lumps = wl == 0 && sum != 0 ? 0 : Noise.Fbm2(x * 0.11 + 5, z * 0.11, 3) * g.GroundBankLumps * wl;
            sum += lumps;
            double wp = JsMath.Smoothstep(g.GroundBankWidth * 0.7, g.GroundBankWidth * 1.8, d);
            double plateau = wp == 0 && sum != 0 ? 0 : Noise.Fbm2(x * 0.035 + 9, z * 0.035, 3) * g.GroundPlateauNoise * wp;
            return sum + plateau;
        }

        /// <summary>Points where the canyon runs out through the hexagon frame.</summary>
        private List<Exit> FindExits()
        {
            var exits = new List<Exit>();
            double inset = Cfg.FrameWallMargin + 1.2;
            foreach (Edge e in Edges)
            {
                for (int pass = 0; pass < 2; pass++)
                {
                    List<double[]> pts = pass == 0 ? e.Pts : JsMath.Reversed(e.Pts);
                    // walk from the inside outward; record the last point before the frame
                    for (int i = 1; i < pts.Count; i++)
                    {
                        bool inA = HexDist(pts[i - 1][0], pts[i - 1][1]) < -inset;
                        bool inB = HexDist(pts[i][0], pts[i][1]) < -inset;
                        if (inA && !inB)
                        {
                            double x = pts[i - 1][0];
                            double z = pts[i - 1][1];
                            double dx = pts[i][0] - x;
                            double dz = pts[i][1] - z;
                            double len = JsMath.OrOne(JsMath.Hypot(dx, dz));
                            bool near = false;
                            foreach (Exit o in exits)
                            {
                                if (JsMath.Hypot(o.X - x, o.Z - z) < 4)
                                {
                                    near = true;
                                    break;
                                }
                            }
                            if (!near) exits.Add(new Exit { X = x, Z = z, DirX = dx / len, DirZ = dz / len, EdgeId = e.Id });
                            break;
                        }
                    }
                }
            }
            return exits;
        }

